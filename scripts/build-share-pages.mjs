import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SHARE_COPIES, SHARE_ICONS, shareRoutePath } from "../share-options.js";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const templatePath = resolve(repoRoot, "index.html");
const publicRoot = new URL("https://markjinli.github.io/hx/");
const nestedBase = "../";

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function replacePattern(markup, pattern, replacement, label) {
  if (!pattern.test(markup)) throw new Error(`Could not replace ${label} in index.html`);
  return markup.replace(pattern, replacement);
}

function replaceMeta(markup, attribute, key, content) {
  const pattern = new RegExp(`<meta\\s+${attribute}="${escapeRegExp(key)}"\\s+content="[^"]*"\\s*/>`);
  return replacePattern(markup, pattern, `<meta ${attribute}="${key}" content="${content}" />`, `${attribute}=${key}`);
}

function replaceLink(markup, relation, href) {
  const pattern = new RegExp(`<link\\s+rel="${escapeRegExp(relation)}"\\s+href="[^"]*"\\s*/>`);
  return replacePattern(markup, pattern, `<link rel="${relation}" href="${href}" />`, `link rel=${relation}`);
}

function routeMarkup(template, icon, copy) {
  const routePath = shareRoutePath(icon.id, copy.id);
  const routeUrl = new URL(routePath, publicRoot).href;
  const imageUrl = new URL(icon.path, publicRoot).href;
  let markup = template;

  markup = replacePattern(
    markup,
    /<html lang="zh-CN" data-base="\.\/" data-share-icon="[^"]+" data-share-copy="[^"]+">/,
    `<html lang="zh-CN" data-base="${nestedBase}" data-share-icon="${icon.id}" data-share-copy="${copy.id}">`,
    "route data",
  );
  markup = replacePattern(markup, /<title>[^<]*<\/title>/, "<title>一份婚礼请帖｜合禧</title>", "title");
  markup = replaceMeta(markup, "name", "description", copy.text);
  markup = replaceMeta(markup, "property", "og:title", "一份婚礼请帖｜合禧");
  markup = replaceMeta(markup, "property", "og:description", copy.text);
  markup = replaceMeta(markup, "property", "og:url", routeUrl);
  markup = replaceMeta(markup, "property", "og:image", imageUrl);
  markup = replaceMeta(markup, "property", "og:image:secure_url", imageUrl);
  markup = replaceMeta(markup, "property", "og:image:alt", `${icon.label}婚礼分享小图`);
  markup = replaceMeta(markup, "itemprop", "image", imageUrl);
  markup = replaceMeta(markup, "name", "twitter:title", "一份婚礼请帖｜合禧");
  markup = replaceMeta(markup, "name", "twitter:description", copy.text);
  markup = replaceMeta(markup, "name", "twitter:image", imageUrl);
  markup = replaceLink(markup, "canonical", routeUrl);
  markup = replaceLink(markup, "image_src", imageUrl);
  markup = replaceLink(markup, "stylesheet", `${nestedBase}styles.css`);
  markup = replacePattern(
    markup,
    /<script type="module" src="\.\/app\.js"><\/script>/,
    `<script type="module" src="${nestedBase}app.js"></script>`,
    "module script",
  );
  markup = markup.replace('href="./" data-builder-link', `href="${nestedBase}" data-builder-link`);
  markup = markup.replaceAll('src="./icons/', `src="${nestedBase}icons/`);
  markup = markup.replaceAll('src="./m.mp3"', `src="${nestedBase}m.mp3"`);
  return markup.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build-share-pages.mjs; edit index.html instead. -->");
}

const template = await readFile(templatePath, "utf8");
let generated = 0;

for (const icon of SHARE_ICONS) {
  for (const copy of SHARE_COPIES) {
    const outputPath = resolve(repoRoot, shareRoutePath(icon.id, copy.id), "index.html");
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, routeMarkup(template, icon, copy), "utf8");
    generated += 1;
  }
}

console.log(`Generated ${generated} static share entry pages.`);
